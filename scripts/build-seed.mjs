#!/usr/bin/env node
// Generates, from migration/base44-export/:
//   - src/lib/content/seed-data.json  (used by the app in CONTENT_SOURCE=seed mode)
//   - supabase/seed.sql               (loads the same data into Supabase/Postgres)
// Usage: node scripts/build-seed.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { transformAll } from "./lib/transform-base44.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => JSON.parse(readFileSync(join(root, p), "utf8"));

const data = transformAll({
  articles: read("migration/base44-export/articles.json"),
  comments: read("migration/base44-export/comments.json"),
  staticContent: read("migration/base44-export/recovered-static-content.json"),
});

writeFileSync(
  join(root, "src/lib/content/seed-data.json"),
  JSON.stringify(data, null, 2) + "\n",
);

// ---- SQL ------------------------------------------------------------------
const q = (v) => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "number") return String(v);
  // Dollar-quote with a tag that cannot appear in content.
  let tag = "ss";
  while (String(v).includes(`$${tag}$`)) tag += "x";
  return `$${tag}$${v}$${tag}$`;
};
const arr = (xs) => `array[${xs.map(q).join(", ")}]::text[]`;
const json = (v) => `${q(JSON.stringify(v))}::jsonb`;

const lines = [
  "-- Generated by scripts/build-seed.mjs from migration/base44-export/. Do not edit by hand.",
  "-- Idempotent: safe to run more than once.",
  "begin;",
];

for (const c of data.categories) {
  lines.push(
    `insert into public.categories (slug, name, short_name, domain_code, description, coming_soon_title, coming_soon_description, sort_order) values (${[
      c.slug, c.name, c.short_name, c.domain_code, c.description, c.coming_soon_title, c.coming_soon_description, c.sort_order,
    ].map(q).join(", ")}) on conflict (slug) do nothing;`,
  );
}
for (const a of data.authors) {
  lines.push(
    `insert into public.authors (id, slug, name, title, initials, bio) values (${[a.id, a.slug, a.name, a.title, a.initials, a.bio].map(q).join(", ")}) on conflict (slug) do nothing;`,
  );
}
for (const a of data.articles) {
  lines.push(
    `insert into public.articles (id, legacy_id, slug, title, excerpt, body, category, author_id, author_name, status, featured, hero_image, hero_image_alt, hero_image_credit, gallery_images, specifications, source_references, tags, seo_title, seo_description, reading_time, published_date, scheduled_date, created_at, updated_at) values (${[
      q(a.id), q(a.legacy_id), q(a.slug), q(a.title), q(a.excerpt), q(a.body), q(a.category), q(a.author_id), q(a.author_name),
      q(a.status), q(a.featured), q(a.hero_image), q(a.hero_image_alt), q(a.hero_image_credit), arr(a.gallery_images),
      json(a.specifications), arr(a.source_references), arr(a.tags), q(a.seo_title), q(a.seo_description), q(a.reading_time),
      a.published_date ? `${q(a.published_date)}::date` : "null",
      a.scheduled_date ? `${q(a.scheduled_date)}::timestamptz` : "null",
      `${q(a.created_at)}::timestamptz`, `${q(a.updated_at)}::timestamptz`,
    ].join(", ")}) on conflict (legacy_id) do nothing;`,
  );
}
for (const c of data.comments) {
  lines.push(
    `insert into public.comments (id, legacy_id, article_id, author_name, content, likes, is_hidden, created_at) values (${[
      q(c.id), q(c.legacy_id), q(c.article_id), q(c.author_name), q(c.content), q(c.likes), q(c.is_hidden), `${q(c.created_at)}::timestamptz`,
    ].join(", ")}) on conflict (legacy_id) do nothing;`,
  );
}
lines.push("commit;", "");
writeFileSync(join(root, "supabase/seed.sql"), lines.join("\n"));

console.log(
  `seed built: ${data.categories.length} categories, ${data.authors.length} authors, ${data.articles.length} articles, ${data.comments.length} comments`,
);
